package introduccion;

public class I09LiteralesYTipo {

	public static void main(String[] args) {
		
		var algo = 456; // algo es int
		var otro = 456.; // otro es double
		
		short s = 456;
		byte b = 116;
		
		long l = 22_200_000_000L;
		
		var otroMas = 456L;  //otroMas es long
		
		//----------------
		
		float f = 1.5F;
		
		var unoMas = 456.0F; // unoMas es float
	}

}
